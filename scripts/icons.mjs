// Inline the used Material Symbols icons into src/icons.js.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
const set = JSON.parse(readFileSync(createRequire(import.meta.url).resolve("@iconify-json/material-symbols/icons.json")));
const USED = ["dashboard-outline", "show-chart", "trending-up", "calendar-month-outline", "table-chart-outline", "star-outline", "flag-outline", "database-outline", "contrast", "download", "keyboard-outline", "push-pin-outline", "push-pin", "person-outline", "chat-outline", "rate-review-outline", "language", "category-outline", "chevron-left", "chevron-right", "percent", "add"];
const out = {};
for (const n of USED) {
  let ic = set.icons[n] ?? (set.aliases?.[n] && set.icons[set.aliases[n].parent]);
  if (!ic) throw new Error(`icon not found: ${n}`);
  out[n] = ic.body;
}
writeFileSync(new URL("../src/icons.js", import.meta.url), `// generated by scripts/icons.mjs (Material Symbols, Apache-2.0)\nexport default ${JSON.stringify(out)};\n`);
console.log(`icons: ${USED.length} inlined`);
